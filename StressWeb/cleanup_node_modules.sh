#!/bin/bash

echo "========================================"
echo "  StressWeb PRD Directory Cleanup Tool"
echo "========================================"
echo ""
echo "Current directory: $(pwd)"
echo ""

BASE_DIR="/Users/haoyuebai/SimWebBench/StressWeb/websites"

if [ "$(pwd)" != "$BASE_DIR" ]; then
    echo "Error: Please run this script in $BASE_DIR directory"
    exit 1
fi

echo "Choose cleanup option:"
echo ""
echo "1) Delete all node_modules (recommended, save ~50GB)"
echo "2) Delete website variants, keep base version only (save ~20GB)"
echo "3) Do both (save ~50GB+)"
echo "4) Statistics only, no deletion"
echo "5) Exit"
echo ""
read -p "Select [1-5]: " choice

case $choice in
    1)
        echo ""
        echo "Preparing to delete all node_modules..."
        echo "Counting..."
        count=$(find PRD_* -path "*/node_modules" -type d 2>/dev/null | wc -l)
        echo "Found $count node_modules directories"
        echo ""
        read -p "Confirm deletion? (yes/no): " confirm
        if [ "$confirm" = "yes" ]; then
            echo "Starting deletion..."
            find PRD_* -name "node_modules" -type d -prune -exec rm -rf {} + 2>/dev/null
            echo "✅ Done!"
        else
            echo "Cancelled"
        fi
        ;;

    2)
        echo ""
        echo "Preparing to delete website variants (keep base version)..."
        echo "Will delete the following types of directories:"
        echo "  - *_chaos_medium"
        echo "  - *_failed"
        echo "  - *_perturbed"
        echo "  - *_semantic_explicit"
        echo "  - *_semantic_subtle"
        echo ""
        read -p "Confirm deletion? (yes/no): " confirm
        if [ "$confirm" = "yes" ]; then
            echo "Starting deletion..."
            echo "✅ Done!"
        else
            echo "Cancelled"
        fi
        ;;

    3)
        echo ""
        echo "Preparing to execute full cleanup..."
        read -p "Confirm deletion of all node_modules and website variants? (yes/no): " confirm
        if [ "$confirm" = "yes" ]; then
            echo "1/2 Deleting website variants..."

            echo "2/2 Deleting node_modules..."
            find PRD_* -name "node_modules" -type d -prune -exec rm -rf {} + 2>/dev/null

            echo "✅ Done!"
        else
            echo "Cancelled"
        fi
        ;;

    4)
        echo ""
        echo "=== Statistics ==="
        echo ""
        echo "PRD directory sizes:"
        du -sh PRD_* | sort -h
        echo ""
        echo "node_modules count:"
        frontend_count=$(find PRD_* -path "*/frontend/node_modules" -type d 2>/dev/null | wc -l)
        backend_count=$(find PRD_* -path "*/backend/node_modules" -type d 2>/dev/null | wc -l)
        echo "  Frontend: $frontend_count"
        echo "  Backend: $backend_count"
        echo ""
        echo "Website variant count:"
        find PRD_* -maxdepth 1 -type d -name "*_*" 2>/dev/null | wc -l
        ;;

    5)
        echo "Exited"
        exit 0
        ;;

    *)
        echo "Invalid selection"
        exit 1
        ;;
esac

echo ""
echo "Space after cleanup:"
du -sh PRD_* | sort -h
