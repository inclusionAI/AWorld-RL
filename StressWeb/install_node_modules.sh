#!/bin/bash

echo "========================================"
echo "  StressWeb Batch node_modules Installation Tool"
echo "========================================"
echo ""

BASE_DIR="/Users/haoyuebai/SimWebBench/StressWeb/websites"

if [ "$(pwd)" != "$BASE_DIR" ]; then
    echo "Error: Please run in $BASE_DIR directory"
    echo "Current directory: $(pwd)"
    echo "Expected directory: $BASE_DIR"
    exit 1
fi

echo "Choose installation option:"
echo ""
echo "1) Install node_modules for all PRD directories"
echo "2) Install base version only (generated-website-query-1)"
echo "3) Install specific PRD directory"
echo "4) Count installations needed"
echo "5) Exit"
echo ""
read -p "Select [1-5]: " choice

count_installations() {
    local pattern=$1
    local frontend_count=$(find PRD_* -path "$pattern/frontend/package.json" 2>/dev/null | wc -l)
    local backend_count=$(find PRD_* -path "$pattern/backend/package.json" 2>/dev/null | wc -l)
    echo "Need to install:"
    echo "  Frontend: $frontend_count "
    echo "  Backend: $backend_count "
    echo "  Total: $((frontend_count + backend_count)) projects"
    echo ""
    echo "Estimated time: ~$((frontend_count * 5 + backend_count * 2)) minutes"
}

install_project() {
    local dir=$1
    local type=$2  # "frontend" or "backend"

    if [ ! -f "$dir/package.json" ]; then
        return 0
    fi

    if [ -d "$dir/node_modules" ]; then
        echo "  ⏭️  node_modules exists, skipping"
        return 0
    fi

    echo "  📦 Installing..."
    cd "$dir"

    if npm install --silent > /tmp/npm_install_$$.log 2>&1; then
        echo "  ✅ Installed successfully"
        rm -f /tmp/npm_install_$$.log
        cd - > /dev/null
        return 0
    else
        echo "  ❌ Installation failed"
        echo "  Error log: /tmp/npm_install_$$.log"
        cd - > /dev/null
        return 1
    fi
}

batch_install() {
    local pattern=$1
    local description=$2

    echo ""
    echo "Starting batch installation: $description"
    echo "================================"
    echo ""

    local total=0
    local success=0
    local failed=0
    local skipped=0

    echo ">>> Step 1/2 Installing Frontend projects"
    echo ""
    for dir in $(find PRD_* -path "$pattern/frontend" -type d 2>/dev/null | sort); do
        total=$((total + 1))
        local prd=$(echo $dir | cut -d'/' -f1)
        local variant=$(echo $dir | cut -d'/' -f2)
        echo "[$total] $prd/$variant/frontend"

        if [ -d "$dir/node_modules" ]; then
            echo "  ⏭️  exists, skipping"
            skipped=$((skipped + 1))
        else
            if install_project "$dir" "frontend"; then
                success=$((success + 1))
            else
                failed=$((failed + 1))
            fi
        fi
        echo ""
    done

    echo ">>> Step 2/2 Installing Backend projects"
    echo ""
    for dir in $(find PRD_* -path "$pattern/backend" -type d 2>/dev/null | sort); do
        total=$((total + 1))
        local prd=$(echo $dir | cut -d'/' -f1)
        local variant=$(echo $dir | cut -d'/' -f2)
        echo "[$total] $prd/$variant/backend"

        if [ -d "$dir/node_modules" ]; then
            echo "  ⏭️  exists, skipping"
            skipped=$((skipped + 1))
        else
            if install_project "$dir" "backend"; then
                success=$((success + 1))
            else
                failed=$((failed + 1))
            fi
        fi
        echo ""
    done

    echo "================================"
    echo "Installation complete!"
    echo ""
    echo "Total: $total projects"
    echo "✅ Success: $success"
    echo "⏭️  Skipped: $skipped"
    echo "❌ Failed: $failed"
}

case $choice in
    1)
        echo ""
        echo "Preparing to install node_modules for all PRD directories..."
        count_installations "*/generated-website-query-1*"
        read -p "Confirm installation? (yes/no): " confirm
        if [ "$confirm" = "yes" ]; then
            batch_install "*/generated-website-query-1*" "all projects"
        else
            echo "Cancelled"
        fi
        ;;

    2)
        echo ""
        echo "Preparing to install node_modules for base version..."
        count_installations "*/generated-website-query-1"
        read -p "Confirm installation? (yes/no): " confirm
        if [ "$confirm" = "yes" ]; then
            batch_install "*/generated-website-query-1" "base version"
        else
            echo "Cancelled"
        fi
        ;;

    3)
        echo ""
        echo "Available PRD directories:"
        ls -d PRD_* 2>/dev/null | nl
        echo ""
        read -p "Enter PRD directory name: " prd_name

        if [ ! -d "$prd_name" ]; then
            echo "Error: directory $prd_name does not exist"
            exit 1
        fi

        echo ""
        count_installations "$prd_name/*"
        read -p "Confirm installation? (yes/no): " confirm
        if [ "$confirm" = "yes" ]; then
            batch_install "$prd_name/*" "$prd_name"
        else
            echo "Cancelled"
        fi
        ;;

    4)
        echo ""
        echo "=== Statistics ==="
        echo ""
        echo "All projects:"
        count_installations "*/generated-website-query-1*"
        echo ""
        echo "Base version only:"
        count_installations "*/generated-website-query-1"
        ;;

    5)
        echo "Exited"
        exit 0
        ;;

    *)
        echo "Invalid selection"
        exit 1
        ;;
esac

echo ""
echo "Completion time: $(date)"
